// The YouTube IFrame API is documented to call window.onYouTubeIframeAPIReady
// automatically once its library has finished loading - but in practice
// that callback can just never fire (observed first-hand: YT.Player was
// fully loaded and working, calling the init logic by hand worked instantly,
// yet the automatic callback never came). Rather than depend on that single
// signal, also poll for window.YT.Player directly and initialize ourselves
// the moment it's available, so a missed callback can't leave the app stuck
// forever on "影片載入中".
const YT_POLL_INTERVAL_MS = 300;
const YT_LOAD_TIMEOUT_MS = 12000;
let ytPollTimer = setInterval(() => {
  if (!player && window.YT && window.YT.Player) initYouTubePlayer();
}, YT_POLL_INTERVAL_MS);
let ytLoadTimeoutId = setTimeout(() => {
  if (!player) {
    statusEl.textContent =
      "影片一直載入不出來，請確認這台裝置可以連上 YouTube 網站（有些家長監控/校園網路會封鎖 YouTube），或換一台裝置、瀏覽器再試試看。";
  }
}, YT_LOAD_TIMEOUT_MS);

// Builds the YouTube player. Normally invoked automatically by the IFrame
// API once it's loaded (via onYouTubeIframeAPIReady below); also invoked by
// the poll above as a fallback in case that automatic callback never fires.
function initYouTubePlayer() {
  if (player) return;
  clearInterval(ytPollTimer);
  player = new YT.Player("yt-player", {
    height: "1",
    width: "1",
    videoId: currentLesson().videoId,
    playerVars: {
      controls: 0,
      disablekb: 1,
      modestbranding: 1,
      rel: 0,
      playsinline: 1,
      fs: 0,
    },
    events: {
      onReady: onPlayerReady,
      onStateChange: onPlayerStateChange,
      onError: onPlayerError,
    },
  });
}

// Called automatically by the YouTube IFrame API script once it has loaded.
function onYouTubeIframeAPIReady() {
  initYouTubePlayer();
}

function onPlayerReady() {
  clearTimeout(ytLoadTimeoutId);
  statusEl.textContent = "準備好了，按「播放」開始聽吧！";
  player.setVolume(Number(volumeSlider.value));
  durationEl.textContent = formatTime((lessonEndSeconds() || player.getDuration()) - lessonStartSeconds());
  setControlsEnabled(true);
  startProgressTimer();
}

function onPlayerError() {
  clearTimeout(ytLoadTimeoutId);
  statusEl.textContent = "影片載入失敗，請檢查網路連線後重新整理頁面。";
  setControlsEnabled(false);
}

function onPlayerStateChange(event) {
  if (event.data === YT.PlayerState.PLAYING) {
    playPauseBtn.innerHTML = "⏸️<br>暫停";
    statusEl.textContent = "正在播放...仔細聽喔！";
    quizSection.hidden = true;
    speakingSection.hidden = true;
    reviewBanner.hidden = true;
    stopMicStream();
    if ("speechSynthesis" in window) speechSynthesis.cancel();
  } else if (event.data === YT.PlayerState.PAUSED) {
    playPauseBtn.innerHTML = "▶️<br>播放";
    statusEl.textContent = "已暫停";
    if (quizSection.hidden && speakingSection.hidden) renderReviewBanner();
  } else if (event.data === YT.PlayerState.ENDED) {
    playPauseBtn.innerHTML = "▶️<br>播放";
    statusEl.textContent = "聽完了！來做個小測驗吧 📝";
    recordLessonCompletion();
    startQuiz();
  }
}

function loadLessonSrsStore() {
  try {
    return JSON.parse(localStorage.getItem(LESSON_SRS_KEY)) || {};
  } catch {
    return {};
  }
}

function saveLessonSrsStore(store) {
  try {
    localStorage.setItem(LESSON_SRS_KEY, JSON.stringify(store));
  } catch {
    // localStorage unavailable (e.g. private mode) - the review table just
    // won't persist, the quiz itself still works fine.
  }
}

function getLessonEntry(store, videoId) {
  if (!store[videoId]) {
    store[videoId] = { reviews: REVIEW_DAY_OFFSETS.map(() => null) };
  }
  return store[videoId];
}

function isSameCalendarDay(ts1, ts2) {
  const d1 = new Date(ts1);
  const d2 = new Date(ts2);
  return (
    d1.getFullYear() === d2.getFullYear() &&
    d1.getMonth() === d2.getMonth() &&
    d1.getDate() === d2.getDate()
  );
}

function getLastRecordedAt(entry) {
  for (let i = entry.reviews.length - 1; i >= 0; i--) {
    if (entry.reviews[i]) return entry.reviews[i];
  }
  return null;
}

function loadDailyMeta() {
  try {
    return JSON.parse(localStorage.getItem(DAILY_META_KEY)) || {};
  } catch {
    return {};
  }
}

function markCompletedToday() {
  try {
    localStorage.setItem(DAILY_META_KEY, JSON.stringify({ lastCompletionAt: Date.now() }));
  } catch {
    // localStorage unavailable - the daily lock just won't persist.
  }
}

function hasCompletedToday() {
  const meta = loadDailyMeta();
  return !!(meta.lastCompletionAt && isSameCalendarDay(meta.lastCompletionAt, Date.now()));
}

// Picks the single lesson unlocked today. Priority: a lesson whose review
// is overdue (the longest-overdue one first) beats a never-started lesson
// (earliest in the list), which beats a lesson whose review is coming up
// soon (soonest first). Once every lesson is either not-yet-due or fully
// graduated, fall back to whichever lesson hasn't been touched in the
// longest time, so there's always exactly one pick.
function getTodaysPickIndex(store) {
  const now = Date.now();
  let overdueBest = null;
  let firstNew = null;
  let upcomingBest = null;
  let staleBest = null;

  LESSONS.forEach((lesson, index) => {
    const entry = getLessonEntry(store, lesson.videoId);
    const nextIdx = entry.reviews.findIndex((v) => !v);

    if (nextIdx === 0) {
      if (firstNew === null) firstNew = index;
      return;
    }
    if (nextIdx === -1) {
      const lastAt = getLastRecordedAt(entry);
      if (!staleBest || lastAt < staleBest.lastAt) staleBest = { index, lastAt };
      return;
    }

    const dueAt = entry.reviews[0] + REVIEW_DAY_OFFSETS[nextIdx] * DAY_MS;
    if (now >= dueAt) {
      if (!overdueBest || dueAt < overdueBest.dueAt) overdueBest = { index, dueAt };
    } else if (!upcomingBest || dueAt < upcomingBest.dueAt) {
      upcomingBest = { index, dueAt };
    }
  });

  if (overdueBest) return overdueBest.index;
  if (firstNew !== null) return firstNew;
  if (upcomingBest) return upcomingBest.index;
  if (staleBest) return staleBest.index;
  return 0;
}

function formatDateShort(ts) {
  const d = new Date(ts);
  return `${d.getMonth() + 1}/${d.getDate()}`;
}

// Records that the lesson was completed just now - called as soon as the
// audio finishes playing (the quiz is optional practice, not a requirement
// for stamping the date), and again if the quiz is finished separately (e.g.
// a table retest that skips straight to the quiz). The very first completion
// stamps today's date straight into the "1" checkpoint; every completion
// after that fills in the next pending 2/4/7/15-day checkpoint with today's
// date - but only once per calendar day, so replaying the audio or retrying
// the quiz right away doesn't let a kid fill in multiple checkpoints at once.
function recordLessonCompletion() {
  markCompletedToday();

  const store = loadLessonSrsStore();
  const entry = getLessonEntry(store, currentLesson().videoId);
  const now = Date.now();

  const lastRecordedAt = getLastRecordedAt(entry);
  if (lastRecordedAt && isSameCalendarDay(lastRecordedAt, now)) return;

  const nextIdx = entry.reviews.findIndex((v) => !v);
  if (nextIdx !== -1) entry.reviews[nextIdx] = now;
  saveLessonSrsStore(store);
}

function toDateInputValue(ts) {
  const d = new Date(ts);
  const pad = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

// Parses a "YYYY-MM-DD" date input value as local noon, so the stamp can't
// slip to a neighbouring day through timezone/DST rounding.
function fromDateInputValue(value) {
  const [y, m, d] = value.split("-").map(Number);
  return new Date(y, m - 1, d, 12).getTime();
}

// Lets a parent stamp a checkpoint by hand - e.g. when the lesson was
// listened to on YouTube directly or on another device, so the automatic
// stamp never happened. Checkpoints stay in order: only an already-stamped
// cell or the next pending one can be set, and the date must fall between
// its neighbours (and not in the future). Clearing a cell also clears every
// later checkpoint, since those were scheduled off of it.
function setLessonCheckpointManually(lessonIndex, checkpointIdx, value) {
  const store = loadLessonSrsStore();
  const entry = getLessonEntry(store, LESSONS[lessonIndex].videoId);

  if (!value) {
    const hasLater = entry.reviews.slice(checkpointIdx + 1).some(Boolean);
    const msg = hasLater
      ? "要清除這個日期嗎？後面的複習日期也會一起清除喔。"
      : "要清除這個日期嗎？";
    if (!confirm(msg)) return renderReviewBanner();
    for (let i = checkpointIdx; i < entry.reviews.length; i++) entry.reviews[i] = null;
  } else {
    const ts = fromDateInputValue(value);
    const prev = checkpointIdx > 0 ? entry.reviews[checkpointIdx - 1] : null;
    const next = entry.reviews[checkpointIdx + 1];
    if (
      ts > Date.now() ||
      (prev && ts < fromDateInputValue(toDateInputValue(prev))) ||
      (next && ts > fromDateInputValue(toDateInputValue(next)))
    ) {
      alert("日期要在前一次和下一次複習之間，而且不能是未來的日子喔！");
      return renderReviewBanner();
    }
    entry.reviews[checkpointIdx] = ts;
    if (isSameCalendarDay(ts, Date.now())) markCompletedToday();
  }

  saveLessonSrsStore(store);
  renderReviewBanner();
}

// Switches the player to a different lesson's video and starts playing it -
// used both for a first listen and for a later review, from the table.
function startLesson(index) {
  if (!player) {
    statusEl.textContent = "影片還沒準備好，請再等一下下，或確認裝置可以連上 YouTube 網站。";
    return;
  }
  currentLessonIndex = index;
  reviewBanner.hidden = true;
  setHomeMode(false);
  player.loadVideoById(videoLoadOptions(LESSONS[index]));
}

// Jumps straight to a lesson's quiz from the review table, skipping the
// video - lets a kid who already knows a lesson retest without re-listening.
// Cues (but doesn't play) the video first so the player still has the right
// lesson loaded if they later hit "重新聽影片" from the quiz result.
function startQuizFromTable(index) {
  currentLessonIndex = index;
  if (player) player.cueVideoById(videoLoadOptions(LESSONS[index]));
  setHomeMode(false);
  startQuiz();
}

// Builds the 內容 / 1 / 2 / 4 / 7 / 15 review table, one row per lesson.
// Column "1" is stamped the moment a lesson is first completed; columns
// 2/4/7/15 are due that many days after the "1" date, and turn into an
// "overdue" warning (instead of a blank dash) once their due date has
// passed without being completed. Today's picked lesson (see
// getTodaysPickIndex) is starred as a recommendation, but every row stays
// clickable - the pick is just a suggestion, not a lock.
function renderReviewBanner() {
  const store = loadLessonSrsStore();
  const completedToday = hasCompletedToday();
  const pickIndex = getTodaysPickIndex(store);
  reviewTableBody.innerHTML = "";

  reviewBannerHint.textContent = completedToday
    ? "🌟 今天已經聽完一課囉！想再聽哪一課都可以～"
    : `👉 今天推薦聽這一課：「${LESSONS[pickIndex].title}」，先養成每天聽英文的習慣！`;

  // Lessons are grouped into series (see each lesson's `series` field),
  // shown as tabs so a kid switches between series instead of scrolling
  // one long list. The selected tab stays in currentSeriesFilter across
  // re-renders (e.g. after finishing a quiz) until another tab is picked.
  // Lessons keep their original LESSONS array index throughout (used for
  // SRS lookups and the start/quiz buttons) - only which rows get built
  // depends on the active tab.
  const allSeries = [...new Set(LESSONS.map((lesson) => lesson.series))];
  if (!allSeries.includes(currentSeriesFilter)) currentSeriesFilter = allSeries[0];

  seriesTabsEl.innerHTML = "";
  allSeries.forEach((series) => {
    const tabBtn = document.createElement("button");
    tabBtn.className = "series-tab-btn" + (series === currentSeriesFilter ? " active" : "");
    tabBtn.textContent = series;
    tabBtn.addEventListener("click", () => {
      currentSeriesFilter = series;
      renderReviewBanner();
    });
    seriesTabsEl.appendChild(tabBtn);
  });

  LESSONS.forEach((lesson, index) => {
    if (lesson.series !== currentSeriesFilter) return;

    const entry = getLessonEntry(store, lesson.videoId);
    const isPick = !completedToday && index === pickIndex;
    const row = document.createElement("tr");
    row.className = isPick ? "review-row-pick" : "";

    const titleCell = document.createElement("td");
    titleCell.className = "review-lesson-cell";
    const titleEl = document.createElement("div");
    titleEl.className = "review-lesson-title";
    titleEl.textContent = (isPick ? "⭐ " : "") + lesson.title;
    const actionsRow = document.createElement("div");
    actionsRow.className = "review-lesson-actions";

    const actionBtn = document.createElement("button");
    actionBtn.className = "review-lesson-btn";
    actionBtn.textContent = entry.reviews[0] ? "🔁 複習" : "▶️ 開始";
    actionBtn.addEventListener("click", () => startLesson(index));

    const quizBtn = document.createElement("button");
    quizBtn.className = "review-lesson-btn review-quiz-btn";
    quizBtn.textContent = "📝 測驗";
    quizBtn.addEventListener("click", () => startQuizFromTable(index));

    const youtubeLink = document.createElement("a");
    youtubeLink.className = "review-lesson-btn review-youtube-link";
    youtubeLink.textContent = "▶️ YouTube";
    youtubeLink.href = lesson.startSeconds
      ? `https://www.youtube.com/watch?v=${lesson.videoId}&t=${lesson.startSeconds}s`
      : `https://www.youtube.com/watch?v=${lesson.videoId}`;
    youtubeLink.target = "_blank";
    youtubeLink.rel = "noopener noreferrer";

    actionsRow.appendChild(actionBtn);
    actionsRow.appendChild(quizBtn);
    actionsRow.appendChild(youtubeLink);
    titleCell.appendChild(titleEl);
    titleCell.appendChild(actionsRow);
    row.appendChild(titleCell);

    const startedAt = entry.reviews[0];
    REVIEW_DAY_OFFSETS.forEach((offsetDays, i) => {
      const cell = document.createElement("td");
      const reviewedAt = entry.reviews[i];
      const isOverdue =
        !reviewedAt && i > 0 && startedAt && Date.now() >= startedAt + offsetDays * DAY_MS;

      if (reviewedAt) {
        cell.className = "review-cell done";
        cell.textContent = formatDateShort(reviewedAt);
      } else if (isOverdue) {
        cell.className = "review-cell overdue";
        cell.textContent = "⚠️";
        cell.title = "已經超過複習時間了，趕快來複習吧！";
      } else {
        cell.className = "review-cell pending";
        cell.textContent = "—";
      }

      // Stamped cells and the next pending one get an invisible date input
      // laid over them, so tapping the cell opens the native date picker.
      const isNextPending = !reviewedAt && (i === 0 || entry.reviews[i - 1]);
      if (reviewedAt || isNextPending) {
        cell.classList.add("editable");
        if (!cell.title) cell.title = "點一下可以手動設定日期";
        const dateInput = document.createElement("input");
        dateInput.type = "date";
        dateInput.className = "review-cell-date-input";
        dateInput.setAttribute("aria-label", `${lesson.title} 第 ${offsetDays} 天的日期`);
        dateInput.max = toDateInputValue(Date.now());
        if (i > 0 && entry.reviews[i - 1]) dateInput.min = toDateInputValue(entry.reviews[i - 1]);
        if (entry.reviews[i + 1]) dateInput.max = toDateInputValue(entry.reviews[i + 1]);
        if (reviewedAt) dateInput.value = toDateInputValue(reviewedAt);
        dateInput.addEventListener("click", () => {
          try {
            dateInput.showPicker();
          } catch {
            // Older browsers open the picker on tap by themselves.
          }
        });
        dateInput.addEventListener("change", () =>
          setLessonCheckpointManually(index, i, dateInput.value)
        );
        cell.appendChild(dateInput);
      }
      row.appendChild(cell);
    });

    reviewTableBody.appendChild(row);
  });
}

function startQuiz() {
  quizIndex = 0;
  quizScore = 0;
  quizResultEl.hidden = true;
  reviewBanner.hidden = true;
  quizSection.hidden = false;
  renderQuizQuestion();
}

function renderQuizQuestion() {
  quizAnswered = false;
  quizFeedbackEl.textContent = "";
  quizFeedbackEl.className = "quiz-feedback";
  quizNextBtn.hidden = true;

  const q = currentLesson().quizQuestions[quizIndex];
  quizProgress.textContent = `第 ${quizIndex + 1} / ${currentLesson().quizQuestions.length} 題`;
  quizQuestionEl.textContent = q.question;
  quizOptionsEl.innerHTML = "";
  q.options.forEach((opt, i) => {
    const btn = document.createElement("button");
    btn.className = "quiz-option-btn";
    btn.textContent = opt;
    btn.addEventListener("click", () => handleQuizAnswer(i));
    quizOptionsEl.appendChild(btn);
  });
}

function handleQuizAnswer(selectedIndex) {
  if (quizAnswered) return;
  quizAnswered = true;

  const q = currentLesson().quizQuestions[quizIndex];
  const isCorrect = selectedIndex === q.answer;
  if (isCorrect) quizScore++;

  const optionButtons = quizOptionsEl.querySelectorAll(".quiz-option-btn");
  optionButtons.forEach((btn, i) => {
    btn.disabled = true;
    if (i === q.answer) btn.classList.add("correct");
    else if (i === selectedIndex) btn.classList.add("wrong");
  });

  quizFeedbackEl.textContent = isCorrect ? "✅ 答對了！太棒了！" : "❌ 答錯囉，正確答案是綠色的選項";
  quizFeedbackEl.className = "quiz-feedback " + (isCorrect ? "correct-text" : "wrong-text");
  quizNextBtn.hidden = false;
  quizNextBtn.textContent = quizIndex < currentLesson().quizQuestions.length - 1 ? "下一題 ➡️" : "看結果 🏆";
}

function showQuizResult() {
  quizProgress.textContent = "";
  quizQuestionEl.textContent = "";
  quizOptionsEl.innerHTML = "";
  quizFeedbackEl.textContent = "";
  quizNextBtn.hidden = true;
  quizResultEl.hidden = false;

  quizScoreEl.textContent = `你答對了 ${quizScore} / ${currentLesson().quizQuestions.length} 題`;
  let msg;
  if (quizScore === currentLesson().quizQuestions.length) {
    msg = "🌟🌟🌟 全部答對！你聽得好仔細！";
  } else if (quizScore >= Math.ceil(currentLesson().quizQuestions.length / 2)) {
    msg = "👍 很不錯喔！再聽一次會更棒！";
  } else {
    msg = "💪 再聽一次，你可以答得更好！";
  }
  quizScoreMsgEl.textContent = msg;

  recordLessonCompletion();
  renderReviewBanner();
}

